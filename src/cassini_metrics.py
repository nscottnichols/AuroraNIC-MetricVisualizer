def _unit(group):
    if group in {'bytes_transferred','bytes_received','bad_octets'}:return 'bytes'
    if group in {'tx_frame_sizes','rx_frame_sizes','pi_posted_pkts','pi_nonposted_pkts'}:return 'packets'
    if group in {'tx_paused_cycles','rx_paused_cycles','oxe_tx_stall','ixe_host_stall','ixe_disp_stall','pi_posted_blocked','pi_nonposted_blocked'}:return 'cycles'
    if group in {'cq_dma_cmd_counts','cq_num_dma_cmds','cq_num_idc_cmds'}:return 'commands'
    return 'events'

